#!/usr/bin/env bash
# scripts/analyze-reports.sh — management-side analyzer (run on schedule or manually).
# Reads uploaded execution reports, regenerates the live wiki, and writes candidate
# knowledge as *proposals* (never auto-active, D19). Repeated candidates (>=2 reports)
# are flagged as `repeat` — the signal to promote a constraint (D4).
# Usage: scripts/analyze-reports.sh [management-repo-dir]
set -euo pipefail
MGMT="${1:-.}"
cd "$MGMT"
mkdir -p wiki/services knowledge/proposals loop/04-build

REPORTS="$(find execution -path '*/reports/*.json' -type f 2>/dev/null | sort || true)"
if [ -z "$REPORTS" ]; then echo "analyze: no reports found"; exit 0; fi

# D4: count candidate titles across ALL reports (project-wide repeat detection).
TITLE_COUNTS="$(jq -s '[ .[] | .spec.candidateKnowledge[]? | .title ] | group_by(.) | map({key: .[0], value: length}) | from_entries' $REPORTS 2>/dev/null || true)"
[ -n "$TITLE_COUNTS" ] || TITLE_COUNTS='{}'

INDEX="wiki/index.md"
{
  echo "# Project Wiki"
  echo ""
  echo "> Generated by analyze-reports.sh at $(date -u +%FT%TZ). Do not edit by hand."
  echo ""
  echo "## Services"
  echo ""
  echo "| Service | Type | Stage | Last report | Review |"
  echo "|---|---|---|---|---|"
} > "$INDEX"

for report_dir in $(find execution -type d -name reports 2>/dev/null | sort); do
  service="$(basename "$(dirname "$report_dir")")"
  stage="$(basename "$(dirname "$(dirname "$report_dir")")")"
  latest="$(for f in "$report_dir"/*.json; do [ -f "$f" ] && printf '%s %s\n' "$(jq -r '.metadata.createdAt // ""' "$f")" "$f"; done | sort | tail -1 | awk '{print $2}')"
  [ -n "$latest" ] || continue
  type="$(jq -r '.metadata.type // "?"' "$latest")"
  review="$(jq -r '.spec.review.status // "auto"' "$latest")"
  echo "| $service | $type | $stage | $(basename "$latest") | $review |" >> "$INDEX"

  {
    echo "# $service"
    echo ""
    echo "- Type: $type"
    echo "- Stage: $stage"
    echo "- Latest report: $(basename "$latest")"
    echo "- Review: $review"
    echo ""
    echo "## Facts"
    echo '```json'
    jq '.spec.facts' "$latest"
    echo '```'
    echo ""
    echo "## Requirements"
    jq -r '.spec.requirementRefs[]? // empty' "$latest" | sed 's/^/- /' || true
    echo ""
    echo "## Decisions"
    jq -r '.spec.decisions[]? | "- \(.id): \(.title) (\(.status))"' "$latest" || true
    echo ""
    echo "## Candidate knowledge"
    jq -r '.spec.candidateKnowledge[]? | "- [\(.type)] \(.title) — \(.proposal)"' "$latest" || true
  } > "wiki/services/$service.md"

  # Candidate knowledge from ALL reports of this service -> proposals.
  for rf in "$report_dir"/*.json; do
    [ -f "$rf" ] || continue
    jq -c '.spec.candidateKnowledge[]?' "$rf" 2>/dev/null | while IFS= read -r item; do
      [ -n "$item" ] || continue
      title="$(echo "$item" | jq -r '.title')"
      type="$(echo "$item" | jq -r '.type')"
      statement="$(echo "$item" | jq -r '.proposal')"
      slug="$(echo "$title" | tr '[:upper:]' '[:lower:]' | tr -cs 'a-z0-9' '-' | sed 's/^-*//; s/-*$//' | cut -c1-40)"
      [ -n "$slug" ] || slug="item"
      prop="knowledge/proposals/P-${service}-${slug}.json"
      count="$(printf '%s' "$TITLE_COUNTS" | jq -r --arg t "$title" '.[$t] // 0')"
      [ -n "$count" ] || count=0
      repeat="false"; [ "${count:-0}" -ge 2 ] && repeat="true"
      if [ ! -f "$prop" ]; then
        jq -n --arg id "P-${service}-${slug}" --arg svc "$service" --arg type "$type" \
          --arg title "$title" --arg stmt "$statement" --arg rep "$(basename "$rf")" \
          --argjson count "$count" --argjson repeat "$repeat" '{
            apiVersion:"sdlc/v1", kind:"KnowledgeProposal", id:$id,
            type:$type, scope:"project", title:$title, statement:$stmt,
            status:"proposed", owner:"", provenance:[("report:"+$rep)],
            repeatCount:$count, repeat:$repeat,
            recommendation:(if $repeat then "promote to constraint (repeated correction)" else "review" end)
          }' > "$prop"
        echo "analyze: proposal -> $prop (repeat=$repeat count=$count)"
      else
        jq --argjson count "$count" --argjson repeat "$repeat" '
          .repeatCount=$count | .repeat=$repeat |
          .recommendation=(if $repeat then "promote to constraint (repeated correction)" else (.recommendation // "review") end)' \
          "$prop" > "$prop.tmp" && mv "$prop.tmp" "$prop"
      fi
    done
  done
done

# Testing summary.
{
  echo "# Testing"
  echo ""
  echo "> Generated by analyze-reports.sh."
  echo ""
  echo "| Service | Unit | Integration | Coverage |"
  echo "|---|---|---|---|"
  for f in $(find execution -path '*/reports/*.json' -type f 2>/dev/null | sort); do
    svc="$(basename "$(dirname "$(dirname "$f")")")"
    u="$(jq -r '.spec.facts.tests.unit // "n/a"' "$f")"
    i="$(jq -r '.spec.facts.tests.integration // "n/a"' "$f")"
    c="$(jq -r '.spec.facts.tests.coverage // "n/a"' "$f")"
    echo "| $svc | $u | $i | $c |"
  done
} > wiki/testing.md

# Test management: loop/05-test/results.md (per-service test facts + requirement refs).
mkdir -p loop/05-test
{
  echo "# Test results"
  echo ""
  echo "> Generated by analyze-reports.sh from execution reports."
  echo ""
  echo "| Service | Unit | Integration | Coverage | Requirements |"
  echo "|---|---|---|---|---|"
  for f in $(find execution -path '*/reports/*.json' -type f 2>/dev/null | sort); do
    svc="$(basename "$(dirname "$(dirname "$f")")")"
    u="$(jq -r '.spec.facts.tests.unit // "n/a"' "$f")"
    i="$(jq -r '.spec.facts.tests.integration // "n/a"' "$f")"
    c="$(jq -r '.spec.facts.tests.coverage // "n/a"' "$f")"
    reqs="$(jq -r '[.spec.requirementRefs[]?] | join(", ")' "$f")"
    echo "| $svc | $u | $i | $c | $reqs |"
  done
} > loop/05-test/results.md

# DORA metrics (derived from reports; lead time / MTTR computed when timestamps exist).
DEPLOYS=0; FAILED_DEPLOYS=0
for f in $(find execution/deploy -path '*/reports/*.json' -type f 2>/dev/null); do
  [ -f "$f" ] || continue
  DEPLOYS=$((DEPLOYS + 1))
  if [ "$(jq -r '.spec.review.status // ""' "$f")" = "needs_review" ]; then
    FAILED_DEPLOYS=$((FAILED_DEPLOYS + 1))
  fi
done
INCIDENTS=0
for f in $(find execution/maintain -path '*/reports/*.json' -type f 2>/dev/null); do
  [ -f "$f" ] && INCIDENTS=$((INCIDENTS + 1))
done
CFR="n/a"; [ "$DEPLOYS" -gt 0 ] && CFR="$(awk -v f="$FAILED_DEPLOYS" -v d="$DEPLOYS" 'BEGIN{printf "%.0f%%", (f/d)*100}')"

# Lead time: earliest build report -> latest deploy report, per deployed service (hours).
LEAD_SUM=0; LEAD_N=0; LEAD_ROWS=""
for svc_dir in execution/deploy/*; do
  [ -d "$svc_dir" ] || continue
  svc="$(basename "$svc_dir")"
  b="$(find "execution/build/$svc/reports" -name '*.json' -type f 2>/dev/null -exec jq -r '.metadata.createdAt // empty' {} \; 2>/dev/null | sort | head -1)"
  d="$(find "$svc_dir/reports" -name '*.json' -type f 2>/dev/null -exec jq -r '.metadata.createdAt // empty' {} \; 2>/dev/null | sort | tail -1)"
  if [ -n "$b" ] && [ -n "$d" ]; then
    h="$(jq -n --arg b "$b" --arg d "$d" '((($d|fromdateiso8601) - ($b|fromdateiso8601)) / 3600 * 10 | round) / 10' 2>/dev/null || echo 0)"
    LEAD_ROWS="${LEAD_ROWS}${LEAD_ROWS:+, }${svc}=${h}h"
    LEAD_SUM="$(awk -v s="$LEAD_SUM" -v h="$h" 'BEGIN{print s + h}')"
    LEAD_N=$((LEAD_N + 1))
  fi
done
LEAD="n/a"
[ "$LEAD_N" -gt 0 ] && LEAD="$(awk -v s="$LEAD_SUM" -v n="$LEAD_N" 'BEGIN{printf "%.1f h", s/n}')"

# MTTR: maintain reports carrying metadata.incident.{openedAt,resolvedAt}; average hours.
MTTR_SUM=0; MTTR_N=0
for f in $(find execution/maintain -path '*/reports/*.json' -type f 2>/dev/null); do
  o="$(jq -r '.metadata.incident.openedAt // empty' "$f" 2>/dev/null || true)"
  r="$(jq -r '.metadata.incident.resolvedAt // empty' "$f" 2>/dev/null || true)"
  if [ -n "$o" ] && [ -n "$r" ]; then
    h="$(jq -n --arg o "$o" --arg r "$r" '((($r|fromdateiso8601) - ($o|fromdateiso8601)) / 3600 * 10 | round) / 10' 2>/dev/null || echo 0)"
    MTTR_SUM="$(awk -v s="$MTTR_SUM" -v h="$h" 'BEGIN{print s + h}')"
    MTTR_N=$((MTTR_N + 1))
  fi
done
MTTR="n/a"
[ "$MTTR_N" -gt 0 ] && MTTR="$(awk -v s="$MTTR_SUM" -v n="$MTTR_N" 'BEGIN{printf "%.1f h", s/n}')"

{
  echo "# DORA metrics"
  echo ""
  echo "> Derived from execution reports. Change failure rate is a proxy; lead time uses build→deploy timestamps; MTTR uses incident opened/resolved timestamps."
  echo ""
  echo "| Metric | Value | Source |"
  echo "|---|---|---|"
  echo "| Deployment frequency | ${DEPLOYS} deploy reports | execution/deploy |"
  echo "| Change failure rate | ${CFR} | deploy reports with review=needs_review (proxy) |"
  echo "| Lead time for changes | ${LEAD} | earliest build → latest deploy per service |"
  echo "| MTTR | ${MTTR} (${INCIDENTS} incidents) | maintain reports with incident timestamps |"
  [ -n "$LEAD_ROWS" ] && echo "| Lead time detail | ${LEAD_ROWS} | per service |"
} > wiki/dora.md

# Cognition dashboard.
{
  echo "# Cognition"
  echo ""
  echo "> Active items come from knowledge/pack.json; proposals await human sign-off (D19)."
  echo "> Repeated proposals (>=2 reports) are flagged — promote them first (D4)."
  echo ""
  echo "## Proposals (pending human sign-off)"
  found=0
  for p in knowledge/proposals/*.json; do
    [ -f "$p" ] || continue
    found=1
    jq -r '"- \(.id) [\(.type)] \(.title) — status: \(.status), repeats: \(.repeatCount // 1)\(if (.repeat // false) then " ⚠ repeated" else "" end)"' "$p"
  done
  [ "$found" -eq 0 ] && echo "_None._"
} > wiki/cognition.md

# Refresh services.json lastReport.
REG="loop/04-build/services.json"
if [ -f "$REG" ]; then
  for report_dir in $(find execution -type d -name reports 2>/dev/null | sort); do
    service="$(basename "$(dirname "$report_dir")")"
    latest="$(for f in "$report_dir"/*.json; do [ -f "$f" ] && printf '%s %s\n' "$(jq -r '.metadata.createdAt // ""' "$f")" "$f"; done | sort | tail -1 | awk '{print $2}')"
    [ -n "$latest" ] || continue
    jq --arg name "$service" --arg last "$latest" --arg ts "$(date -u +%FT%TZ)" \
      '(.services[] | select(.name == $name)) |= (. + {lastReport:$last, updatedAt:$ts})' \
      "$REG" > "$REG.tmp" && mv "$REG.tmp" "$REG"
  done
fi

echo "analyze: wiki updated ($(find wiki/services -name '*.md' 2>/dev/null | wc -l | tr -d ' ') service pages, $(find knowledge/proposals -name '*.json' 2>/dev/null | wc -l | tr -d ' ') proposals)"
