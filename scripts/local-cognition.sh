#!/usr/bin/env bash
# scripts/local-cognition.sh — service-local (S1) cognition.
#
# S1 rules live and are enforced only in this service repo. Their normative
# statement never leaves the repo: collect reports origin/problem/summary/gate
# evidence only, and nothing here is synced from the control plane.
#
# Usage:
#   local-cognition.sh add --statement <s> --problem <p> [--kind k]
#        [--enforcement advisory|deterministic] [--origin-type t] [--origin-ref r]
#        [--summary s] [--gate-type t] [--gate-name n] [--gate-path p]
#        [--evidence e]... [--owner o] [--json]
#   local-cognition.sh list [--status s] [--json]
#   local-cognition.sh show <id> [--json]
#   local-cognition.sh deprecate <id> [--json]
#   local-cognition.sh render
#   local-cognition.sh path
#
# deterministic items must name a real gate (--gate-type plus --gate-name/--gate-path).
set -euo pipefail
ROOT="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
FILE="$ROOT/.sdlc/local-cognition.json"
[ -d "$ROOT/.sdlc" ] || { echo "ERROR: not a service repo (no .sdlc/)" >&2; exit 1; }
SERVICE="$(jq -r '.service // empty' "$ROOT/.sdlc/config.json" 2>/dev/null || true)"
[ -n "$SERVICE" ] || SERVICE="$(jq -r '.name // empty' "$ROOT/service.json" 2>/dev/null || true)"
[ -n "$SERVICE" ] || SERVICE="service"
NOW="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
MAX_SUMMARY=200

init() {
  [ -f "$FILE" ] && return 0
  jq -n --arg svc "$SERVICE" \
    '{apiVersion:"sdlc/v1",kind:"LocalCognition",service:$svc,items:[]}' > "$FILE"
}

render() {
  local block; block="$(mktemp)"
  {
    printf '<!-- BEGIN LOCAL COGNITION (generated by local-cognition.sh; do not edit) -->\n'
    printf '## 本服务本地认知（S1，只在本仓生效）\n\n'
    if [ "$(jq '[.items[]|select(.status=="active")]|length' "$FILE")" = "0" ]; then
      printf '当前无 active 本地规则。\n'
    else
      jq -r '.items[]|select(.status=="active")|"- [\(.enforcement)] \(.statement)（\(.id)）"' "$FILE"
      printf '\n> 规则正文不上报；collect 只上报 origin/problem/summary/gate 证据。\n'
      printf '> 查询：bash scripts/local-cognition.sh list --json\n'
    fi
    printf '<!-- END LOCAL COGNITION -->\n'
  } > "$block"
  local f
  for f in "$ROOT/CLAUDE.md" "$ROOT/AGENTS.md"; do
    python3 - "$f" "$block" <<'PY'
import os, re, sys
path, block_path = sys.argv[1], sys.argv[2]
text = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
block = open(block_path, encoding="utf-8").read()
pattern = re.compile(r"<!-- BEGIN LOCAL COGNITION.*?<!-- END LOCAL COGNITION -->", re.S)
if pattern.search(text):
    text = pattern.sub(lambda _m: block, text)
    text = re.sub(r"(<!-- END LOCAL COGNITION -->)\s*$", r"\1\n", text)
else:
    text = (text.rstrip() + "\n\n" + block) if text.strip() else block
if not text.endswith("\n"):
    text += "\n"
open(path, "w", encoding="utf-8").write(text)
PY
  done
  rm -f "$block"
}

cmd="${1:-}"; shift || true
case "$cmd" in
  path) init; echo "$FILE"; exit 0 ;;
esac
[ -n "$cmd" ] || { sed -n '2,22p' "$0" >&2; exit 1; }
init

case "$cmd" in
  add)
    KIND="constraint"; ENF="advisory"; STMT=""; PROBLEM=""; SUMMARY=""
    ORIGIN_TYPE="manual"; ORIGIN_REF=""; OWNER=""
    GATE_TYPE=""; GATE_NAME=""; GATE_PATH=""; EVIDENCE=""; JSON=0
    while [ $# -gt 0 ]; do
      case "$1" in
        --kind) KIND="${2:-}"; shift 2 ;;
        --enforcement) ENF="${2:-}"; shift 2 ;;
        --statement) STMT="${2:-}"; shift 2 ;;
        --problem) PROBLEM="${2:-}"; shift 2 ;;
        --summary) SUMMARY="${2:-}"; shift 2 ;;
        --origin-type) ORIGIN_TYPE="${2:-}"; shift 2 ;;
        --origin-ref) ORIGIN_REF="${2:-}"; shift 2 ;;
        --gate-type) GATE_TYPE="${2:-}"; shift 2 ;;
        --gate-name) GATE_NAME="${2:-}"; shift 2 ;;
        --gate-path) GATE_PATH="${2:-}"; shift 2 ;;
        --evidence) EVIDENCE="${EVIDENCE}${EVIDENCE:+$'\n'}${2:-}"; shift 2 ;;
        --owner) OWNER="${2:-}"; shift 2 ;;
        --json) JSON=1; shift ;;
        *) echo "local-cognition: unknown option $1" >&2; exit 1 ;;
      esac
    done
    [ -n "$STMT" ] || { echo "local-cognition: add needs --statement" >&2; exit 1; }
    [ -n "$PROBLEM" ] || { echo "local-cognition: add needs --problem (what it solves)" >&2; exit 1; }
    [ -n "$SUMMARY" ] || SUMMARY="$PROBLEM"
    case "$KIND" in constraint|decision|context|skill|lesson) ;; *)
      echo "local-cognition: invalid --kind '$KIND'" >&2; exit 1 ;; esac
    case "$ENF" in advisory|deterministic) ;; *)
      echo "local-cognition: --enforcement must be advisory|deterministic" >&2; exit 1 ;; esac
    if [ "$ENF" = "deterministic" ]; then
      [ -n "$GATE_TYPE" ] && { [ -n "$GATE_NAME" ] || [ -n "$GATE_PATH" ]; } || {
        echo "local-cognition: deterministic needs --gate-type plus --gate-name or --gate-path" >&2
        exit 1; }
    fi
    LEN="$(printf '%s' "$SUMMARY" | wc -m | tr -d ' ')"
    [ "$LEN" -le "$MAX_SUMMARY" ] || {
      echo "local-cognition: --summary is $LEN chars (max $MAX_SUMMARY); keep it a short context note" >&2
      exit 1; }
    SEQ="$(jq '[.items[].id | capture("-(?<n>[0-9]+)$").n | tonumber] | (max // 0) + 1' "$FILE" 2>/dev/null || echo 1)"
    ID="$(printf 'L-%s-%03d' "$SERVICE" "$SEQ")"
    EV_JSON="$(printf '%s\n' "$EVIDENCE" | jq -R -s 'split("\n")|map(select(length>0))')"
    tmp="$(mktemp)"
    jq --arg id "$ID" --arg kind "$KIND" --arg enf "$ENF" --arg stmt "$STMT" \
      --arg problem "$PROBLEM" --arg summary "$SUMMARY" --arg ot "$ORIGIN_TYPE" \
      --arg orf "$ORIGIN_REF" --arg gt "$GATE_TYPE" --arg gn "$GATE_NAME" --arg gp "$GATE_PATH" \
      --arg owner "$OWNER" --arg at "$NOW" --argjson ev "$EV_JSON" '
      .items += [{
        id:$id, scope:"service", kind:$kind, enforcement:$enf, statement:$stmt,
        origin:{type:$ot, ref:$orf, at:$at},
        problem:$problem, summary:$summary,
        gate:(if ($gt=="" and $gn=="" and $gp=="") then null
              else {type:$gt,name:$gn,path:$gp} end),
        evidence:$ev, owner:$owner, status:"active", createdAt:$at
      }]' "$FILE" > "$tmp" && mv "$tmp" "$FILE"
    render
    if [ "$JSON" = 1 ]; then jq --arg id "$ID" '.items[]|select(.id==$id)' "$FILE"
    else echo "local-cognition: added $ID ($ENF) $STMT"; fi
    ;;
  list)
    STATUS=""; JSON=0
    while [ $# -gt 0 ]; do
      case "$1" in
        --status) STATUS="${2:-}"; shift 2 ;;
        --json) JSON=1; shift ;;
        *) echo "local-cognition: unknown option $1" >&2; exit 1 ;;
      esac
    done
    if [ "$JSON" = 1 ]; then
      jq --arg st "$STATUS" '[.items[]|select($st=="" or .status==$st)]' "$FILE"
    else
      jq -r --arg st "$STATUS" '.items[]|select($st=="" or .status==$st)
        |"\(.id)  \(.enforcement)  \(.status)  \(.kind)  \(.statement)"' "$FILE"
    fi
    ;;
  show)
    ID="${1:-}"; JSON=0; [ "${2:-}" = "--json" ] && JSON=1
    [ -n "$ID" ] || { echo "local-cognition: show needs an id" >&2; exit 1; }
    if [ "$JSON" = 1 ]; then jq --arg id "$ID" '.items[]|select(.id==$id)' "$FILE"
    else jq -r --arg id "$ID" '.items[]|select(.id==$id)
      |"\(.id)\n  statement: \(.statement)\n  problem: \(.problem)\n  summary: \(.summary // "")\n  evidence: \([.evidence[]?]|join(", "))\n  status: \(.status)"' "$FILE"; fi
    ;;
  deprecate)
    ID="${1:-}"; JSON=0; [ "${2:-}" = "--json" ] && JSON=1
    [ -n "$ID" ] || { echo "local-cognition: deprecate needs an id" >&2; exit 1; }
    tmp="$(mktemp)"
    jq --arg id "$ID" --arg at "$NOW" \
      '(.items[]|select(.id==$id)) |= (.status="deprecated" | .deprecatedAt=$at)' "$FILE" > "$tmp" && mv "$tmp" "$FILE"
    render
    if [ "$JSON" = 1 ]; then jq --arg id "$ID" '.items[]|select(.id==$id)' "$FILE"
    else echo "local-cognition: deprecated $ID"; fi
    ;;
  render) render; echo "local-cognition: rendered into CLAUDE.md / AGENTS.md" ;;
  *) sed -n '2,22p' "$0" >&2; exit 1 ;;
esac
