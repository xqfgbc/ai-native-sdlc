#!/usr/bin/env bash
# scripts/sync-cognition.sh — distribute the project's cognition pack to a service repo
# (local simulation of the P3 "cognition pack version lock" flow).
# Usage: scripts/sync-cognition.sh <management-repo> <service-repo>
set -euo pipefail
MGMT="${1:-}"; SVC="${2:-}"
[ -n "$MGMT" ] && [ -n "$SVC" ] && [ -d "$SVC" ] || {
  echo "Usage: $0 <management-repo> <service-repo>" >&2; exit 1; }
PACK="$(cd "$MGMT" && pwd)/knowledge/pack.json"
[ -f "$PACK" ] || { echo "ERROR: missing $PACK" >&2; exit 1; }
[ -f "$SVC/service.json" ] || { echo "ERROR: $SVC is not a service repo (no service.json)" >&2; exit 1; }

mkdir -p "$SVC/.sdlc"
cp "$PACK" "$SVC/.sdlc/cognition-pack.json"
VER="$(jq -r '.metadata.version' "$PACK")"
jq --arg v "$VER" '.cognitionPack.version = $v' "$SVC/service.json" > "$SVC/service.json.tmp"
mv "$SVC/service.json.tmp" "$SVC/service.json"
# Keep the collector metadata in step with the pinned pack version.
if [ -f "$SVC/.sdlc/config.json" ]; then
  jq --arg v "$VER" '.cognitionPack.version = $v' "$SVC/.sdlc/config.json" > "$SVC/.sdlc/config.json.tmp"
  mv "$SVC/.sdlc/config.json.tmp" "$SVC/.sdlc/config.json"
fi

# Surface the signed cognition where agents actually read it: CLAUDE.md/AGENTS.md
# (auto-loaded / protocol file) and a standalone context file.
render_block() {
  local file="$1" block
  block="$(mktemp)"
  {
    printf '<!-- BEGIN COGNITION PACK v%s (generated by sync-cognition.sh; do not edit) -->\n' "$VER"
    printf '## 项目认知（人工签核 active）\n\n'
    if [ "$(jq '[.items[]|select(.status=="active")]|length' "$SVC/.sdlc/cognition-pack.json")" = "0" ]; then
      printf '当前无 active 条目。\n'
    else
      jq -r '.items[]|select(.status=="active")|"- [\(.enforcement)] \(.statement // .title)（\(.id)）"' "$SVC/.sdlc/cognition-pack.json"
      printf '\n> deterministic 条目由对应 hook/ArchUnit/lint/CI 强制；advisory 条目按此执行。\n'
      printf '> 查询：bash scripts/cognition.sh list --json\n'
    fi
    printf '<!-- END COGNITION PACK -->\n'
  } > "$block"
  python3 - "$file" "$block" <<'PY'
import os, re, sys
path, block_path = sys.argv[1], sys.argv[2]
text = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
block = open(block_path, encoding="utf-8").read()
pattern = re.compile(r"<!-- BEGIN COGNITION PACK.*?<!-- END COGNITION PACK -->", re.S)
if pattern.search(text):
    text = pattern.sub(lambda _m: block, text)
else:
    text = (text.rstrip() + "\n\n" + block) if text.strip() else block
if not text.endswith("\n"):
    text += "\n"
open(path, "w", encoding="utf-8").write(text)
PY
  rm -f "$block"
}
render_block "$SVC/CLAUDE.md"
render_block "$SVC/AGENTS.md"
cp "$SVC/.sdlc/cognition-pack.json" "$SVC/.sdlc/cognition.md" 2>/dev/null || true
echo "synced cognition pack v$VER -> $SVC/.sdlc/cognition-pack.json (service.json pinned)"
